CT = {'i': 'int', 'u': 'unsigned', 'b': 'unsigned char', 'f': 'float', 'p': 'void *', 's': 'ptrdiff_t', 'v': 'void'}

funcs = []
for line in SPEC.strip().splitlines():
    parts = line.split()
    special = parts[-1] == 'SPECIAL'
    if special:
        parts = parts[:-1]
    funcs.append((parts[0], parts[1], parts[2:], special))

out = sys.argv[1]
with open(out + '/gl_names.h', 'w') as f:
    f.write('// Generated by tools/gen_gl.py. Order is the call number shared by guest and host.\n')
    f.write('#define GL_COUNT %d\n' % len(funcs))
    f.write('static const char *const GL_NAMES[GL_COUNT] = {\n')
    for ret, name, args, special in funcs:
        f.write('    "%s",\n' % name)
    f.write('};\n')

with open(out + '/gl_gen.inc', 'w') as f:
    f.write('// Generated by tools/gen_gl.py.\n')
    for ret, name, args, special in funcs:
        if special:
            continue
        f.write('static %s (GLAPIENTRY *p_%s)(%s);\n' % (CT[ret], name, ', '.join(CT[a] for a in args) or 'void'))
    f.write('static void gl_load(void) {\n')
    for ret, name, args, special in funcs:
        if not special:
            f.write('    p_%s = (void *)SDL_GL_GetProcAddress("%s");\n' % (name, name))
    f.write('}\n')
    f.write('static uint64_t gl_dispatch(int idx, const uint64_t *x, uint64_t sp) {\n    switch (idx) {\n')
    for idx, (ret, name, args, special) in enumerate(funcs):
        if special:
            f.write('    case %d: return sp_%s(x, sp);\n' % (idx, name))
            continue
        ni = nf = 0
        exprs = []
        for a in args:
            if a == 'f':
                exprs.append('F(%d)' % nf); nf += 1
                continue
            src = 'x[%d]' % ni if ni < 8 else 'STK(%d)' % (ni - 8)
            ni += 1
            exprs.append({'i': '(int)%s', 'u': '(unsigned)%s', 'b': '(unsigned char)%s', 'p': 'g2h(%s)', 's': '(ptrdiff_t)%s'}[a] % src)
        call = 'p_%s(%s)' % (name, ', '.join(exprs))
        if ret == 'v':
            f.write('    case %d: if (p_%s) %s; return 0;\n' % (idx, name, call))
        else:
            f.write('    case %d: return p_%s ? (uint64_t)%s : 0;\n' % (idx, name, call))
    f.write('    }\n    return 0;\n}\n')
print(len(funcs), 'GL functions')
